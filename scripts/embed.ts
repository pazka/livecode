// Embeds the built front-end (dist/web + web/) into src/server/assets.gen.ts: content hashes for cache busting,
// a gzip copy of each text asset. Run by `deno task build`. Permissions: read dist/ + web/, write the outputs.

import { repairInteropHelper } from "./bundlefix.ts";

/** gzOnly: embedded gzipped only (a large file: the server inflates it for a client without gzip). */
type Entry = [path: string, file: string, type: string, immutable: boolean, gzOnly?: boolean];

const files: Entry[] = [
  ["/index.html", "dist/web/index.html", "text/html; charset=utf-8", false],
  ["/app.js", "dist/web/app.js", "text/javascript; charset=utf-8", true],
  ["/app.css", "web/app.css", "text/css; charset=utf-8", true],
  ["/favicon.svg", "web/favicon.svg", "image/svg+xml", true],
  ["/preview.html", "dist/web/preview.html", "text/html; charset=utf-8", false],
  ["/preview.js", "web/preview.js", "text/javascript; charset=utf-8", true],
  // TypeScript compiler + the browser's type definitions: loaded when a room needs it (TypeScript, format)
  ["/ts-worker.js", "dist/web/ts-worker.js", "text/javascript; charset=utf-8", true, true],
];

async function hash(b: Uint8Array<ArrayBuffer>) {
  const d = new Uint8Array(await crypto.subtle.digest("SHA-256", b));
  return [...d.slice(0, 6)].map((x) => x.toString(16).padStart(2, "0")).join("");
}

function b64(b: Uint8Array): string {
  let s = "";
  for (let i = 0; i < b.length; i += 0x8000) s += String.fromCharCode(...b.subarray(i, i + 0x8000));
  return btoa(s);
}

async function gzip(b: Uint8Array<ArrayBuffer>): Promise<Uint8Array> {
  const stream = new Blob([b]).stream().pipeThrough(new CompressionStream("gzip"));
  return new Uint8Array(await new Response(stream).arrayBuffer());
}

/** A file's bytes; a JavaScript bundle is repaired on the way (bundlefix.ts: a `deno bundle --minify` bug). */
const cache = new Map<string, Uint8Array<ArrayBuffer>>();
async function read(file: string): Promise<Uint8Array<ArrayBuffer>> {
  let b = cache.get(file);
  if (!b) {
    b = await Deno.readFile(file);
    if (file.startsWith("dist/") && file.endsWith(".js")) {
      const { js, repaired } = repairInteropHelper(new TextDecoder().decode(b));
      if (repaired) {
        console.log(`${file}: repaired the CommonJS helper broken by the minifier (${repaired}×)`);
        b = new TextEncoder().encode(js);
      }
    }
    cache.set(file, b);
  }
  return b;
}

const js = await read("dist/web/app.js");
const css = await read("web/app.css");
const pjs = await read("web/preview.js");
const tsw = await read("dist/web/ts-worker.js");
const html = (await Deno.readTextFile("web/index.html"))
  .replace("@@JS_HASH@@", await hash(js))
  .replace("@@CSS_HASH@@", await hash(css))
  .replace("@@TSW_HASH@@", await hash(tsw));
await Deno.writeTextFile("dist/web/index.html", html);
const preview = (await Deno.readTextFile("web/preview.html")).replace("@@PREVIEW_HASH@@", await hash(pjs));
await Deno.writeTextFile("dist/web/preview.html", preview);

let out = "// GENERATED by scripts/embed.ts — do not edit, do not commit.\n";
out +=
  "export const ASSETS: Record<string, { type: string; b64?: string; gz?: string; immutable: boolean }> = {\n";
for (const [path, file, type, immutable, gzOnly] of files) {
  const body = await read(file);
  const gz = type.startsWith("image/") ? null : await gzip(body);
  out += `  ${JSON.stringify(path)}: { type: ${JSON.stringify(type)}, immutable: ${immutable}${
    gzOnly && gz ? "" : `, b64: "${b64(body)}"`
  }${gz ? `, gz: "${b64(gz)}"` : ""} },\n`;
}
out += "};\n";
await Deno.writeTextFile("src/server/assets.gen.ts", out);
console.log(
  `embedded ${files.length} files, app.js ${(js.length / 1024).toFixed(0)} KiB, ts-worker.js ${
    (tsw.length / 1024).toFixed(0)
  } KiB`,
);
