// Writes src/client/ts/libs.gen.ts: the TypeScript lib files the script sees (LIB_ROOTS of service.ts and
// every lib they reference), read from the pinned `typescript` package, for the TypeScript worker. Run by
// `deno task build`. Permissions: read the package (in Deno's cache), write the output.

import { LIB_ROOTS } from "../src/client/ts/service.ts";

const dir = new URL("./", import.meta.resolve("typescript")); // …/typescript/<version>/lib/
const version =
  (JSON.parse(await Deno.readTextFile(new URL("../package.json", dir))) as { version: string }).version;
const libs: Record<string, string> = {};
const todo: string[] = [...LIB_ROOTS];
while (todo.length) {
  const name = todo.pop()!;
  if (name in libs) continue;
  const text = await Deno.readTextFile(new URL(name, dir));
  libs[name] = text;
  for (const m of text.matchAll(/\/\/\/\s*<reference\s+lib="([^"]+)"/g)) {
    todo.push(`lib.${m[1].toLowerCase()}.d.ts`);
  }
}

const names = Object.keys(libs).sort();
let out =
  "// GENERATED by scripts/tslibs.ts from the pinned typescript package — do not edit, do not commit.\n";
out += `// TypeScript ${version} (Apache-2.0, Microsoft): ${names.length} lib files.\n`;
out += "export const TS_VERSION = " + JSON.stringify(version) + ";\n";
out += "export const LIBS: Record<string, string> = {\n";
for (const n of names) out += `  ${JSON.stringify(n)}: ${JSON.stringify(libs[n])},\n`;
out += "};\n";
await Deno.writeTextFile("src/client/ts/libs.gen.ts", out);
const kib = names.reduce((s, n) => s + libs[n].length, 0) / 1024;
console.log(`TypeScript ${version}: ${names.length} lib files, ${kib.toFixed(0)} KiB`);
